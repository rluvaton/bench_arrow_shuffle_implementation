/// A row-oriented representation of arrow data, that is normalized for comparison.
///
/// See the [module level documentation](self) and [`UnorderedRowConverter`] for more details.
#[derive(Debug)]
pub struct UnorderedRows {
    /// Underlying row bytes
    buffer: Vec<u8>,
    /// Row `i` has data `&buffer[offsets[i]..offsets[i+1]]`
    offsets: Vec<usize>,
    /// The config for these rows
    config: UnorderedRowConfig,
}

impl UnorderedRows {
    /// Append a [`UnorderedRow`] to this [`UnorderedRows`]
    pub fn push(&mut self, row: UnorderedRow<'_>) {
        // TODO - returned this
        // assert!(
        //     Arc::ptr_eq(&row.config.fields, &self.config.fields),
        //     "row was not produced by this RowConverter"
        // );
        self.config.validate_utf8 |= row.config.validate_utf8;
        self.buffer.extend_from_slice(row.data);
        self.offsets.push(self.buffer.len())
    }

    /// Return the length of each row in this [`Rows`]
    pub fn lengths(&self) -> impl ExactSizeIterator<Item = usize> + '_ {
        self.offsets.windows(2).map(|x| x[1] - x[0])
    }
    /// Return the length of each row in this [`Rows`]
    pub fn lengths_from(&self, data_range: &Range<usize>) -> impl ExactSizeIterator<Item = usize> + '_ {
        self.offsets[data_range.start..].windows(2).map(|x| x[1] - x[0]).take(data_range.len())
    }

    /// Returns the row at index `row`
    pub fn row(&self, row: usize) -> UnorderedRow<'_> {
        assert!(row + 1 < self.offsets.len());
        unsafe { self.row_unchecked(row) }
    }

    /// Returns the row at `index` without bounds checking
    ///
    /// # Safety
    /// Caller must ensure that `index` is less than the number of offsets (#rows + 1)
    pub unsafe fn row_unchecked(&self, index: usize) -> UnorderedRow<'_> {
        let end = unsafe { self.offsets.get_unchecked(index + 1) };
        let start = unsafe { self.offsets.get_unchecked(index) };
        let data = unsafe { self.buffer.get_unchecked(*start..*end) };
        UnorderedRow {
            data,
            config: &self.config,
        }
    }

    /// Get data for rows in start..end
    pub(crate) fn data_range(&self, data_range: Range<usize>) -> &[u8] {
        assert!(data_range.start < self.offsets.len());
        assert!(data_range.end < self.offsets.len());
        // We want to exclude end, so we take the one before it
        let end_row = data_range.end - 1;

        {
            let end = unsafe { self.offsets.get_unchecked(end_row + 1) };
            let start = unsafe { self.offsets.get_unchecked(data_range.start) };
            let data = unsafe { self.buffer.get_unchecked(*start..*end) };

            data
        }
        //
        // let start = self.offsets[data_range.start];
        // let end = self.offsets[data_range.end];
        // &self.buffer[start..end]
    }

    /// Get the number of bytes the rows will take
    pub(crate) fn data_range_len(&self, data_range: &Range<usize>) -> usize {
        assert!(data_range.start < self.offsets.len());
        assert!(data_range.end < self.offsets.len());
        // We want to exclude end, so we take the one before it
        let end_row = data_range.end - 1;

            let end = unsafe { self.offsets.get_unchecked(end_row + 1) };
            let start = unsafe { self.offsets.get_unchecked(data_range.start) };

            *end - *start
    }

    /// Sets the length of this [`UnorderedRows`] to 0
    pub fn clear(&mut self) {
        self.offsets.truncate(1);
        self.buffer.clear();
    }

    /// Returns the number of [`UnorderedRow`] in this [`UnorderedRows`]
    pub fn num_rows(&self) -> usize {
        self.offsets.len() - 1
    }

    /// Returns an iterator over the [`UnorderedRow`] in this [`UnorderedRows`]
    pub fn iter(&self) -> UnorderedRowsIter<'_> {
        self.into_iter()
    }

    /// Returns the size of this instance in bytes
    ///
    /// Includes the size of `Self`.
    pub fn size(&self) -> usize {
        // Size of fields is accounted for as part of RowConverter
        std::mem::size_of::<Self>()
            + self.buffer.capacity()
            + self.offsets.capacity() * std::mem::size_of::<usize>()
    }

    /// Create a [BinaryArray] from the [UnorderedRows] data without reallocating the
    /// underlying bytes.
    ///
    ///
    /// ```
    /// # use std::sync::Arc;
    /// # use std::collections::HashSet;
    /// # use arrow_array::cast::AsArray;
    /// # use arrow_array::StringArray;
    /// # use arrow_row::{OwnedRow, Row, RowConverter, RowParser, SortField};
    /// # use arrow_schema::DataType;
    /// #
    /// let converter = RowConverter::new(vec![SortField::new(DataType::Utf8)]).unwrap();
    /// let array = StringArray::from(vec!["hello", "world", "a", "a", "hello"]);
    /// let rows = converter.convert_columns(&[Arc::new(array)]).unwrap();
    ///
    /// // We can convert rows into binary format and back.
    /// let values: Vec<OwnedRow> = rows.iter().map(|r| r.owned()).collect();
    /// let binary = rows.try_into_binary().expect("known-small array");
    /// let parser = converter.parser();
    /// let parsed: Vec<OwnedRow> =
    ///   binary.iter().flatten().map(|b| parser.parse(b).owned()).collect();
    /// assert_eq!(values, parsed);
    /// ```
    ///
    /// # Errors
    ///
    /// This function will return an error if there is more data than can be stored in
    /// a [BinaryArray] -- i.e. if the total data size is more than 2GiB.
    pub fn try_into_binary(self) -> Result<BinaryArray, ArrowError> {
        if self.buffer.len() > i32::MAX as usize {
            return Err(ArrowError::InvalidArgumentError(format!(
                "{}-byte rows buffer too long to convert into a i32-indexed BinaryArray",
                self.buffer.len()
            )));
        }
        // We've checked that the buffer length fits in an i32; so all offsets into that buffer should fit as well.
        let offsets_scalar = ScalarBuffer::from_iter(self.offsets.into_iter().map(i32::usize_as));
        // SAFETY: offsets buffer is nonempty, monotonically increasing, and all represent valid indexes into buffer.
        let array = unsafe {
            BinaryArray::new_unchecked(
                OffsetBuffer::new_unchecked(offsets_scalar),
                Buffer::from_vec(self.buffer),
                None,
            )
        };
        Ok(array)
    }
}

impl<'a> IntoIterator for &'a UnorderedRows {
    type Item = UnorderedRow<'a>;
    type IntoIter = UnorderedRowsIter<'a>;

    fn into_iter(self) -> Self::IntoIter {
        UnorderedRowsIter {
            rows: self,
            start: 0,
            end: self.num_rows(),
        }
    }
}

/// An iterator over [`UnorderedRows`]
#[derive(Debug)]
pub struct UnorderedRowsIter<'a> {
    rows: &'a UnorderedRows,
    start: usize,
    end: usize,
}

impl<'a> Iterator for UnorderedRowsIter<'a> {
    type Item = UnorderedRow<'a>;

    fn next(&mut self) -> Option<Self::Item> {
        if self.end == self.start {
            return None;
        }

        // SAFETY: We have checked that `start` is less than `end`
        let row = unsafe { self.rows.row_unchecked(self.start) };
        self.start += 1;
        Some(row)
    }

    fn size_hint(&self) -> (usize, Option<usize>) {
        let len = self.len();
        (len, Some(len))
    }
}

impl ExactSizeIterator for UnorderedRowsIter<'_> {
    fn len(&self) -> usize {
        self.end - self.start
    }
}

impl DoubleEndedIterator for UnorderedRowsIter<'_> {
    fn next_back(&mut self) -> Option<Self::Item> {
        if self.end == self.start {
            return None;
        }
        // Safety: We have checked that `start` is less than `end`
        let row = unsafe { self.rows.row_unchecked(self.end) };
        self.end -= 1;
        Some(row)
    }
}

